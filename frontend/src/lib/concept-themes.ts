/** AI 应用侧族名: 该族所有来源标签的成分股都按 AI_HARDWARE_TAGS 过滤 */
const AI_APP_FAMILY = 'AI应用/大模型'

/**
 * 分隔符碎片标签: THEME_MAP 里的这些 key 并不是独立题材, 而是含空格/斜杠的
 * 标签被前端 SEPARATORS 拆开后产生的残片 ("AI PC" → "AI" + "PC")。
 * 在「逐股展示精准题材」的场景 (连板天梯) 必须一并过滤, 否则会出现
 * "AI"/"PC"/"6" 这类无意义标签。
 */
const FRAGMENT_LABELS: ReadonlySet<string> = new Set(['AI', 'PC', 'WiFi', '6', 'DRG', 'DIP'])

/**
 * 该标签是否属于「非题材噪声」—— 属性桶 (融资融券/深股通/地区/持股…) 或分隔符碎片。
 * 逐股展示题材的场合 (连板天梯) 用它过滤; 概念分析页则用 EXCLUDED_LABELS 整组丢弃。
 */
export function isThemeNoiseLabel(label: string): boolean {
  const t = label.trim()
  return EXCLUDED_LABELS.has(t) || FRAGMENT_LABELS.has(t)
}

/** 与 analysis-adapter.SEPARATORS 保持一致 (含 \s 与 /, 故 "WiFi 6" 会被拆开) */
const CONCEPT_SEPARATORS = /[、,，;；|/\s]+/

/**
 * 由 ext 行构建「标的 → 其全部概念标签」索引, 供 refine 做标签交集判定。
 * field = 实际使用的维度字段名 (通常是「所属概念」)。
 */
export function buildLabelIndex(
  rows: Record<string, unknown>[],
  field: string,
): Map<string, Set<string>> {
  const index = new Map<string, Set<string>>()
  for (const row of rows) {
    const symbol = String((row as { symbol?: unknown }).symbol ?? (row as { code?: unknown }).code ?? '')
    if (!symbol) continue
    const raw = row[field]
    if (raw == null) continue
    const set = index.get(symbol) ?? new Set<string>()
    for (const part of String(raw).split(CONCEPT_SEPARATORS)) {
      const label = part.trim()
      if (label) set.add(label)
    }
    index.set(symbol, set)
  }
  return index
}

/**
 * 对 parsePerStock 产出的分组做「属性过滤 + 同族合并」。
 * - 命中 EXCLUDED_LABELS 的组丢弃
 * - 命中 THEME_MAP 的组并入族: 成分股按 symbol 去重取并集 (一只股同时属于
 *   重组蛋白与 CRO 时, 在「创新药/医药」里只计一次)
 * - 「AI应用/大模型」族 (family === AI_APP_FAMILY) 的成分股, 若带 AI_HARDWARE_TAGS
 *   任一标签则剔除 (需传入 labelIndex; 未传时该族不做过滤, 调用方应尽量传入)
 * - 输出按成员数降序, 与 parsePerStock 排序口径一致
 * metrics 由页面统计层 (calcConceptStat) 基于 stocks 重算, 这里置空即可。
 */
export function refineConceptGroups<T extends { key: string; count: number; stocks: { symbol?: string }[] }>(
  groups: T[],
  labelIndex?: Map<string, Set<string>>,
): T[] {
  const merged = new Map<string, T>()
  const seen = new Map<string, Set<string>>() // 族名 → 已收 symbol

  for (const g of groups) {
    if (EXCLUDED_LABELS.has(g.key)) continue
    const family = THEME_MAP[g.key] ?? g.key
    // AI应用/大模型 族: 按个股其他标签剔除算力硬件侧 (动态分流, 非主观分类)。
    // 覆盖该族全部来源标签 (人工智能宽泛桶 + 13 个 AI 子题), 否则子题标签仍会带入硬件股。
    const drop = family === AI_APP_FAMILY
      ? (s: { symbol?: string }) => {
          if (!labelIndex) return false
          const labels = labelIndex.get(String(s.symbol ?? ''))
          if (!labels) return false
          for (const t of labels) if (AI_HARDWARE_TAGS.has(t)) return true
          return false
        }
      : null
    const incoming = drop ? g.stocks.filter(s => !drop(s)) : g.stocks
    const acc = merged.get(family)
    if (!acc) {
      const rows = [...incoming]
      const syms = new Set<string>()
      for (const s of rows) {
        const sym = String(s.symbol ?? '')
        if (sym) syms.add(sym)
      }
      merged.set(family, { ...g, key: family, stocks: rows, count: rows.length })
      seen.set(family, syms)
      continue
    }
    const syms = seen.get(family)!
    const accRows = acc.stocks as T['stocks']
    for (const s of incoming) {
      const sym = String(s.symbol ?? '')
      if (!sym) {
        accRows.push(s)
        continue
      }
      if (syms.has(sym)) continue
      syms.add(sym)
      accRows.push(s)
    }
    acc.count = accRows.length
  }

  return [...merged.values()].sort((a, b) => b.stocks.length - a.stocks.length)
}
